const {chromium} = require('../production/remotion/node_modules/playwright-core');
const {pathToFileURL} = require('url');
const path = require('path');
const fs = require('fs');
const os = require('os');
const assert = require('assert').strict;
(async () => {
  const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'panel-profile-'));
  const options = {headless: true, executablePath: process.env.CHROMIUM_PATH || undefined, args:['--no-sandbox']};
  let context = await chromium.launchPersistentContext(profile, options), page = await context.newPage();
  const url = pathToFileURL(path.resolve(__dirname, '../teslim/kadinca-yasam-icerik-paneli.html')).href;
  await page.goto(url); await page.locator('#page-size').selectOption('10');
  await page.click('#next'); await page.click('[data-expand="VID-011"]');
  await page.locator('#VID-011-title').fill('Kalıcı metin'); await page.locator('[data-done="VID-011"]').check();
  await page.click('#to-settings'); await page.locator('#choices input[value=title]').check();
  await page.locator('[data-visible-field="tags"]').uncheck(); await page.locator('#separator').selectOption('pipe');
  await page.reload(); assert.equal(await page.locator('#settings-page').isVisible(), true);
  assert.equal(await page.locator('#choices input[value=title]').isChecked(), true);
  assert.equal(await page.locator('[data-visible-field="tags"]').isChecked(), false);
  assert.equal(await page.locator('#separator').inputValue(), 'pipe');
  await context.close();
  context = await chromium.launchPersistentContext(profile, options); page = await context.newPage(); await page.goto(url);
  assert.equal(await page.locator('#settings-page').isVisible(), true);
  assert.equal(await page.locator('#choices input[value=title]').isChecked(), true);
  await page.click('#nav-list'); assert.equal(await page.locator('#page-size').inputValue(),'10');
  assert.ok((await page.locator('#page-label').textContent()).startsWith('2 /'));
  assert.equal(await page.locator('[data-expand="VID-011"]').getAttribute('aria-expanded'),'true');
  assert.equal(await page.locator('#VID-011-title').inputValue(),'Kalıcı metin');
  assert.equal(await page.locator('[data-done="VID-011"]').isChecked(),true);
  await page.locator('#search').fill('VID-011'); await page.locator('#filter').selectOption('done'); await page.reload();
  assert.equal(await page.locator('#search').inputValue(),'VID-011'); assert.equal(await page.locator('#filter').inputValue(),'done');
  assert.equal(await page.locator('#save-status').textContent(),'✓ Yerel kayıt açık');
  await context.close(); fs.rmSync(profile,{recursive:true,force:true});
  const browser = await chromium.launch(options); const blocked = await browser.newContext(); const failedPage = await blocked.newPage();
  await failedPage.addInitScript(() => { Storage.prototype.setItem = function(){throw new DOMException('Storage unavailable', 'QuotaExceededError')}; });
  await failedPage.goto(url);
  assert.equal(await failedPage.locator('#storage-warning').isVisible(),true);
  assert.equal(await failedPage.locator('#save-status').textContent(),'Yerel kayıt kapalı');
  await failedPage.click('[data-expand="VID-001"]'); await failedPage.locator('#VID-001-title').fill('Kayıt dışı taslak');
  await failedPage.click('#to-settings'); const [download] = await Promise.all([failedPage.waitForEvent('download'), failedPage.click('#export')]);
  const saved=JSON.parse(fs.readFileSync(await download.path(),'utf8')); assert.equal(saved.state.edits['VID-001'].title,'Kayıt dışı taslak');
  await browser.close(); console.log('Yeniden açma ve yerel kayıt engellendiğinde yedek indirme doğrulandı.');
})().catch(e=>{console.error(e);process.exit(1)});
